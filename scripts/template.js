/* 纯函数模板层：只从入参取值，不读全局、不 require 内容文件、不碰文件系统。
   产物零外部依赖；首页允许一段内联 canvas 脚本（见 docs/superpowers/specs/2026-10-14-swimming-shark-design.md），
   详情页仍然零 JavaScript —— 无 <script>/无 fetch/无外链字体，全部产物可直接从 file:// 打开。 */
const { esc } = require('./util.js');
const { categoryName } = require('./curate.js');

const DOCTYPE = '<!DOCTYPE html>';
const GENERATED = '<!-- GENERATED BY scripts/build.js — 请勿手改 -->';
/* 详情页「模块」列表的上屏上限：页面标题可能上百条，整列会淹没这一节。 */
const MODULE_LIMIT = 16;

/* bodyClass 首段为 case-study 时，同目录下的资源（样式表、favicon）都要退一级目录（详情页在 case/ 下）。
   注意用前缀判断而不是 === 'case-study'：详情页的 bodyClass 是 `case-study c-<slug>`，
   精确等值会让它链到 case/css/style.css 而丢样式（Task 6 裁定把 slug 类挂上 body 后新增的形态）。
   同一个 prefix 也喂给 favicon —— 两处相对路径只有一套口径，不会出现一个退一级一个不退。 */
function layout({ title, description, bodyClass = '', inner, shark = '' }) {
  const prefix = bodyClass.split(' ')[0] === 'case-study' ? '../' : '';
  return `${GENERATED}
${DOCTYPE}
<html lang="zh-CN">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="${esc(description)}">
<title>${esc(title)}</title>
<link rel="icon" href="${prefix}img/favicon.png">
<link rel="stylesheet" href="${prefix}css/style.css">
</head>
<body${bodyClass ? ` class="${bodyClass}"` : ''}>
${shark ? sharkCanvas() : ''}
${inner}
${shark ? sharkScript(shark) : ''}
</body>
</html>
`;
}

const masthead = (name, tagline, avatar) => `<header class="masthead">
${avatar ? `<img class="avatar" src="${esc(avatar)}" alt="${esc(name)}" width="48" height="48">` : ''}
<h1>${esc(name)}</h1>
<p class="muted">${esc(tagline)}</p>
</header>`;

/* 首页巡游鲨鱼：canvas 放 body 最前，脚本放最后。
   motion 是 scripts/shark-motion.js 剥掉 CommonJS 导出后的原样源码 ——
   测的那份与跑的那份是同一段文字，这里只写 DOM 胶水。 */
const sharkCanvas = () => '<canvas class="shark" aria-hidden="true" width="0" height="0"></canvas>';

function sharkScript(motion) {
  /* 'use strict'; 必须是 IIFE 的第一行 —— 放在插值进来的运动源码之后就不在指令序列里，
     整段会以 sloppy 模式运行（2026-10-14 Task 4 评审裁定，重排后 400 帧轨迹逐位不变）。 */
  return `<script>
(function () {
'use strict';
${motion}
var canvas = document.querySelector('canvas.shark');
if (!canvas || !canvas.getContext) return;
if (window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
var ctx = canvas.getContext('2d');
/* getContext 存在 ≠ 拿得到上下文：浏览器耗尽画布上下文时它返回 null，那是文档化行为。
   装饰动效拿不到上下文就整个不启动，而不是让 render 第一帧就抛。
   （反过来不给 requestAnimationFrame 加存在性判断：没有 rAF 的浏览器也没有可用的 canvas。） */
if (!ctx) return;
/* 种子按天稳定：同一天内刷新，鲨鱼的起点与朝向一致（否则每刷一次就换一个地方，
   截图核对与观感调试全被打断），隔天换一条路线。
   不用 sessionStorage 存坐标（那能做到「刷新后接着游」）—— 本站产物必须在 file:// 下可用，
   而 file:// 是不透明源，那边存储会直接抛 SecurityError，为一个装饰动效不值。 */
var rand = mulberry32(Math.floor(Date.now() / 864e5) >>> 0);
var pointer = null, state = null, raf = 0, last = 0;
function view() {
  var w = Math.max(1, window.innerWidth), h = Math.max(1, window.innerHeight);
  return { w: w, h: h, dpr: Math.min(window.devicePixelRatio || 1, 2),
    dark: !!(window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches) };
}
function size() {
  var v = view();
  canvas.width = Math.round(v.w * v.dpr);
  canvas.height = Math.round(v.h * v.dpr);
  canvas.style.width = v.w + 'px';
  canvas.style.height = v.h + 'px';
  state = state ? clampInto(state, v) : initialState(v, rand);
}
function frame(now) {
  var v = view();
  var dt = last ? (now - last) / 1000 : 1 / 60;
  last = now;
  state = step(state, v, dt, rand, pointer);
  render(ctx, state, v);
  raf = window.requestAnimationFrame(frame);
}
function start() { if (!raf) { last = 0; raf = window.requestAnimationFrame(frame); } }
function stop() { if (raf) { window.cancelAnimationFrame(raf); raf = 0; } }
window.addEventListener('resize', size);
window.addEventListener('pointermove', function (e) { pointer = { x: e.clientX, y: e.clientY }; });
window.addEventListener('pointerdown', function (e) {
  pointer = { x: e.clientX, y: e.clientY };
  state = pulse(state);
});
window.addEventListener('pointerout', function () { pointer = null; });
window.addEventListener('blur', function () { pointer = null; });
document.addEventListener('visibilitychange', function () { if (document.hidden) stop(); else start(); });
size();
start();
})();
</script>`;
}

const row = (label, inner) => `<section class="row"><h2>${esc(label)}</h2><div>${inner}</div></section>`;

function indexItem({ monogram, name, oneLine, meta, href, slug }) {
  const cls = slug ? `c-${slug}` : '';
  const cells = `<span class="num">[${esc(monogram)}]</span><span class="client">${esc(name)}</span>`
    + `<span class="title">${esc(oneLine)}</span><span class="role">${esc(meta)}</span>`;
  return `<li>${href
    ? `<a href="${esc(href)}" class="${cls}">${cells}</a>`
    : `<span class="${['cell', cls].filter(Boolean).join(' ')}">${cells}</span>`}</li>`;
}

const plainItem = (left, right) => `<li><span>${esc(left)}</span><span class="muted">${esc(right)}</span></li>`;
const groupLabel = (name) => `<p class="group">${esc(name)}</p>`;

function homePage(ctx) {
  const { site, featured, stats } = ctx;
  const rows = [];

  if (site.about) rows.push(row('关于', `<p>${esc(site.about)}</p>`));
  if (site.now) rows.push(row('近期', `<p>${esc(site.now)}</p>`));

  if (featured.length) {
    rows.push(row('精选项目', `<ol class="index">${featured.map(indexItem).join('')}</ol>`));
  }

  const exp = (site.experience || []).filter((e) => e.name && e.note);
  if (exp.length) {
    rows.push(row('经历', `<ol class="index">${exp.map((e) => indexItem({
      monogram: e.monogram, name: e.name, oneLine: e.note, meta: e.meta, href: '', slug: '',
    })).join('')}</ol>`));
  }

  const groups = (site.techStack || []).filter((g) => (g.items || []).length);
  if (groups.length) {
    rows.push(row('技术', groups.map((g) => groupLabel(g.name)
      + `<ul class="plain">${g.items.map((item) => plainItem(item, '')).join('')}</ul>`).join('')));
  }

  const c = site.contact || {};
  const links = [
    c.email ? ['邮箱', `<a href="mailto:${esc(c.email)}" class="hl">${esc(c.email)}</a>`] : null,
    c.wechat ? ['微信', `<span class="hl">${esc(c.wechat)}</span>`] : null,
    c.github ? ['GitHub', `<a href="https://${esc(c.github)}" rel="noopener noreferrer" class="hl">${esc(c.github)}</a>`] : null,
    c.phone ? ['电话', esc(c.phone)] : null,
  ].filter(Boolean);
  if (links.length) {
    rows.push(row('联系', `<ul class="plain">${links.map(([k, v]) => `<li><span class="muted">${k}</span><span>${v}</span></li>`).join('')}</ul>`));
  }

  return layout({
    title: `${site.name} | ${site.tagline}`,
    description: `${site.name} — ${site.tagline}，${stats.projects} 个小程序与 H5 项目`,
    inner: `${masthead(site.name, site.tagline, site.avatar)}\n<main>\n${rows.join('\n')}\n</main>`,
    shark: ctx.sharkMotion || '',
  });
}

function casePage(ctx) {
  const { feat, facts } = ctx;
  /* 分包为 0 时省略这一段：与概览句（build.js factsFor.summary 的 `record.subPackages ? … : ''`）同一口径。
     同一页上两套说法会让读者困惑，而 `16 页 · 0 分包` 里的 0 会被读成缺陷 —— 「没有分包」没有信息量。 */
  const meta = [`${facts.pages} 页`, facts.subPackages ? `${facts.subPackages} 分包` : '', categoryName(facts.category)]
    .filter(Boolean).join(' · ');
  /* 截断必须显式说明：读者需要知道这 16 条是样本而不是全部模块。一句「共 N 个页面标题，示例 16 个」即可；
     没被截断（含恰好 16 条）时不多写这句。用 .stats 而非裸 .muted —— 它自带 1rem 下间距。 */
  const titles = facts.pageTitles;
  const shownTitles = titles.slice(0, MODULE_LIMIT);
  const cutNote = titles.length > shownTitles.length
    ? `<p class="stats">共 ${titles.length} 个页面标题，示例 ${shownTitles.length} 个</p>` : '';
  const inner = `<div class="cs-head">
<a class="back" href="../index.html">返回</a>
<div class="cs-line"><span class="cs-key">[${esc(feat.monogram)}]</span><span class="cs-company">${esc(feat.name)}</span>
<span class="cs-meta">${esc(meta)} · ${esc(facts.lastCommit)}</span></div>
</div>
<hr class="dashed">
<main>
<h1 class="cs-title">${esc(feat.oneLine)}</h1>
${row('概览', `<p>${esc(feat.oneLine)}</p><p class="muted">${esc(facts.summary)}</p>`)}
${feat.points.length ? row('要点', `<ul class="plain">${feat.points.map((p) => plainItem(p.text, '')).join('')}</ul>`) : ''}
${facts.signals.length ? row('技术', `<ul class="plain">${facts.signals.map((s) => plainItem(s, '')).join('')}</ul>`) : ''}
${titles.length ? row('模块', cutNote + `<ul class="plain">${shownTitles.map((t) => plainItem(t, '')).join('')}</ul>`) : ''}
${row('下一节', `<p><a class="ul" href="../index.html">回到首页</a></p>`)}
</main>`;
  return layout({ bodyClass: `case-study c-${feat.slug}`, title: `${feat.name} | ${feat.oneLine}`, description: feat.oneLine, inner });
}

/* layout 仅本模块内部使用（homePage/casePage 调用），全仓 grep 无外部/测试引用，故不再导出。 */
module.exports = { row, indexItem, plainItem, homePage, casePage, sharkCanvas, sharkScript };
